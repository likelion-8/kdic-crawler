"""되묻기(clarification) — 업무가 특정되지 않은 질문에 업무 선택 버튼으로 되묻는다.

## 왜 필요한가 (2026-08-20 실측)

"신청 링크 알려줘"처럼 업무(주제)가 빠진 질문은, 코퍼스에서 '신청'의 지배 주제가
착오송금이라 검색이 항상 착오송금 페이지를 top 으로 뽑는다 — 사용자가 예금보험금이나
미수령금을 물은 것이어도 착오송금으로 단정한 답이 나간다. 신청 링크·절차는 업무별로
따로 있으므로, 추측하지 말고 어느 업무인지 되묻는 것이 맞다.

## 판정은 LLM(query_rewriter), 이 모듈은 페이로드만

1차 시도(키워드 판정, 2026-08-20 폐기)의 교훈: 정규식은 의도를 구분하지 못한다 —
"내가 신청한 결과 언제 받아요?"(진행상황)를 "신청 링크 줘"(링크 요청)와 같게 보고
오발동했고, 배제형 변형("다른 업무 신청 링크" → "다른 업무에 대해서도")이 나올 때마다
규칙을 덧대는 두더지잡기가 됐다.

2차 시도(정규식 프리스크린 + 전용 LLM 콜, 2026-08-21 폐기)의 교훈: 판정을 LLM 에 넘겨도
**그 LLM 을 부를지 정규식이 정하면 같은 문제가 남는다.** _INTENT_HINT_RE 에 힌트 낱말이
없는 질문("얼마까지 가능해?", "얼마나걸려요")은 판정을 아예 못 받고 코퍼스 편향대로
착오송금으로 단정 답변이 나갔다(실측 5건, query_cache 에 그대로 쌓여 있었다).

3차 시도(첫 턴은 플래너 · 후속 턴은 재작성기로 나눠 얹기, 2026-08-21~08-25)의 교훈:
**판정을 어느 콜에 얹느냐보다 그 콜이 게이트보다 앞인지가 중요하다.** 플래너는 Gate 2
뒤라, 업무 명사가 빠진 질문("신청 방법 알려줘", "신청서 양식 주세요")이 Gate 2 에서 먼저
범위외로 EXIT 돼 판정 기회 자체가 없었다 — Gate 2 in_domain 참조 62문장이 전부 업무 명사를
달고 있어 '도메인 밖'과 '업무 미정'이 코사인으로 안 갈린다(실측 s_id 0.536 < s_ood 0.668,
최근접 클러스터 human_agent_proxy_request). 참조 사전 교정은 s_id 를 모든 절차형 질문에
대해 올려 차단력을 깎으므로 택하지 않았다.

지금은 판정이 **게이트 앞에서 도는 질문 정리 콜 하나**에 필드로 얹혀 있다
(query_rewriter.RewriteResult.needs_clarification, api/rag/sse.py 0-2.5 → 0-2.7). 첫 턴·후속
턴이 같은 경로를 돌고 판정은 턴당 한 번이며 정규식은 없다. 대가는 첫 턴 LLM +1콜이다
(종전 첫 턴은 0콜이었다 — 2026-08-25 팀 결정으로 감수).

프론트 계약(api/schemas/chat.py Clarification): done.clarification 이 있으면 answer 는
버려지고 options 가 버튼으로 그려진다. 되묻기 턴에는 answer_delta 를 보내면 안 된다.
버튼 클릭은 label 을 그대로 다음 메시지로 보낸다(CB-005 §3.7-1) — 그 턴에는 이력
(원래 질문 + 되묻기)이 있으므로 질문 정리 콜이 원래 질문과 선택 업무를 합성한다. 그래서
label 은 완전한 문장이 아니라 **업무명**이다(1차 시도의 '완전한 질문 문장' value 는
원래 질문 의도를 바꿔치기하는 문제가 있었다).
"""
# ── 되묻기 페이로드 ──────────────────────────────────────────────────────────────

CLARIFY_QUESTION = "어떤 업무를 찾고 계신가요? 아래에서 골라주시면 바로 안내해 드릴게요."

# label 은 버튼 문구이자 클릭 시 그대로 전송되는 업무명. 업무를 특정하는 낱말을 반드시
# 포함해야 한다 — 클릭으로 온 턴을 판정기가 다시 "업무 미정"으로 보면 되묻기가 무한 반복된다.
# 예금자보호제도는 신청 절차가 없어(한도 내 자동 적용) 처음엔 뺐다가 2026-08-25 에 넣었다 —
# 판정 프롬프트(query_planner / query_rewriter)는 업무를 6개로 놓고 "어느 업무인지 모르겠다"고
# 판정하는데 선택지가 5개면, 한도·자격·대상을 묻는 질문("얼마까지 가능해?")에서 사용자가
# 원한 업무(예금자보호일 확률이 가장 높다)가 버튼에 없어 되묻기가 헛발이 된다. 판정 목록과
# 선택지는 같은 집합이어야 한다. "신청 링크 줘" → 예금자보호제도 클릭은 "별도 신청 없이
# 자동 보호" 안내로 답이 나오므로 오답이 아니다.
CLARIFY_OPTIONS = [
    {"label": "착오송금 반환지원"},
    {"label": "예금보험금·가지급금"},
    {"label": "미수령금 찾기"},
    {"label": "은닉재산 신고"},
    {"label": "채무조정"},
    {"label": "예금자보호제도"},
]


def clarification_payload() -> dict:
    """api/schemas/chat.py 의 Clarification 과 같은 모양의 되묻기 페이로드."""
    return {"question": CLARIFY_QUESTION, "options": [dict(o) for o in CLARIFY_OPTIONS]}
