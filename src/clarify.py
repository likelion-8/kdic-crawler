"""되묻기(clarification) — 업무가 특정되지 않은 질문에 업무 선택 버튼으로 되묻는다.

## 왜 필요한가 (2026-08-20 실측)

"신청 링크 알려줘"처럼 업무(주제)가 빠진 질문은, 코퍼스에서 '신청'의 지배 주제가
착오송금이라 검색이 항상 착오송금 페이지를 top 으로 뽑는다 — 사용자가 예금보험금이나
미수령금을 물은 것이어도 착오송금으로 단정한 답이 나간다. 신청 링크·절차는 업무별로
따로 있으므로, 추측하지 말고 어느 업무인지 되묻는 것이 맞다.

## 판정은 LLM(query_rewriter), 이 모듈은 프리스크린과 페이로드만

1차 시도(키워드 판정, 2026-08-20 폐기)의 교훈: 정규식은 의도를 구분하지 못한다 —
"내가 신청한 결과 언제 받아요?"(진행상황)를 "신청 링크 줘"(링크 요청)와 같게 보고
오발동했고, 배제형 변형("다른 업무 신청 링크" → "다른 업무에 대해서도")이 나올 때마다
규칙을 덧대는 두더지잡기가 됐다. 그래서 판정은 멀티턴 재작성기(query_rewriter)의
구조화 출력에 needs_clarification 필드로 얹었다 — 후속 턴은 어차피 돌던 콜이라 +0콜,
첫 턴만 아래 프리스크린을 통과한 후보에 한해 +1콜(triage_first_turn)이다.

프론트 계약(api/schemas/chat.py Clarification): done.clarification 이 있으면 answer 는
버려지고 options 가 버튼으로 그려진다. 되묻기 턴에는 answer_delta 를 보내면 안 된다.
버튼 클릭은 label 을 그대로 다음 메시지로 보낸다(CB-005 §3.7-1) — 그 턴에는 이력
(원래 질문 + 되묻기)이 있으므로 재작성기가 원래 질문과 선택 업무를 합성한다. 그래서
label 은 완전한 문장이 아니라 **업무명**이다(1차 시도의 '완전한 질문 문장' value 는
원래 질문 의도를 바꿔치기하는 문제가 있었다).
"""
import re

# ── 첫 턴 프리스크린 — LLM 판정 후보만 거른다(재현율 우선, 정밀도는 LLM 몫) ──────────

# 업무를 전제로 하는 질문의 흔한 낱말. 여기 걸려도 발동이 아니라 'LLM 에게 물어볼 후보'일
# 뿐이다 — "내가 신청한 결과 언제 받아요?" 같은 오탐은 LLM 이 걸러낸다.
_INTENT_HINT_RE = re.compile(r"신청|접수|링크|절차|서류|신고|자격|결과|기한")

# 업무를 특정하는 낱말이 하나라도 보이면 후보에서 뺀다 — 업무가 이미 정해진 질문이라
# LLM 을 부를 이유가 없다(첫 턴 대부분이 여기서 걸러져 0콜 유지). 넓게 잡는다.
_TOPIC_RE = re.compile(
    r"착오송금|송금|잘못\s*보|반환|"          # 착오송금 반환지원
    r"예금|보험금|가지급|보호|파산|저축은행|"   # 예금보험금·예금자보호
    r"미수령|"                                # 고객 미수령금
    r"은닉|재산|포상|"                        # 은닉재산 신고
    r"채무|조정|대출|신용|상속"                # 채무조정 등
)


def first_turn_candidate(question: str) -> bool:
    """첫 턴 질문이 LLM 되묻기 판정(triage_first_turn)을 받을 후보인가.

    업무 전제 낱말이 있고 업무 특정 낱말이 하나도 없을 때만 True — 대부분의 첫 턴은
    False 라 LLM 콜이 붙지 않는다(query_rewriter 의 "첫 턴 0콜" 약속 유지)."""
    return bool(_INTENT_HINT_RE.search(question)) and not _TOPIC_RE.search(question)


# ── 되묻기 페이로드 ──────────────────────────────────────────────────────────────

CLARIFY_QUESTION = "어떤 업무를 찾고 계신가요? 아래에서 골라주시면 바로 안내해 드릴게요."

# label 은 버튼 문구이자 클릭 시 그대로 전송되는 업무명. 각 label 은 _TOPIC_RE 에 걸리는
# 낱말을 포함해야 한다 — 클릭으로 온 턴이 다시 프리스크린 후보가 되는 루프 방지(테스트 고정).
# 예금자보호제도는 신청 절차가 없어(한도 내 자동 적용) 선택지에서 뺐다 — 넣을지는 팀 미결.
CLARIFY_OPTIONS = [
    {"label": "착오송금 반환지원"},
    {"label": "예금보험금·가지급금"},
    {"label": "미수령금 찾기"},
    {"label": "은닉재산 신고"},
    {"label": "채무조정"},
]


def clarification_payload() -> dict:
    """api/schemas/chat.py 의 Clarification 과 같은 모양의 되묻기 페이로드."""
    return {"question": CLARIFY_QUESTION, "options": [dict(o) for o in CLARIFY_OPTIONS]}
